using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Esatto.Umbraco.Backoffice.SeoReport.Tests.Support;
using Xunit;

namespace Esatto.Umbraco.Backoffice.SeoReport.Tests;

/// <summary>
/// The client's types (types.ts) and the server's answers are written by hand on two sides, and nothing else would notice when they drift.
/// So the server's REAL answers (<see cref="RealResponses"/>: the controller over the test rig, the report the mapper builds for a golden
/// scenario with a brand split and warnings, the analysis over synthetic archived months) are written into
/// <c>Client/src/testing/server-responses.ts</c> as constants of the types in types.ts (<c>export const report: ReportResponse = {...}</c>:
/// an object literal checked against its declared type, which is as strict as <c>satisfies</c> and leaves the constant usable as that type).
/// tsc, part of <c>npm run build</c>, then fails on a member the client does not know, one it expects and does not get, or a null where it
/// expects none; and <c>contract.test.ts</c> runs them through the client's own modules and texts.
///
/// This test fails when the committed file no longer holds what the server answers today. To write it again, run the C# tests with the
/// environment variable <c>UPDATE_SERVER_RESPONSES=1</c> (for example <c>UPDATE_SERVER_RESPONSES=1 dotnet test --filter
/// ServerResponsesFileTests</c>) and commit the file with the change that made it differ.
/// </summary>
public class ServerResponsesFileTests
{
    private const string UpdateVariable = "UPDATE_SERVER_RESPONSES";

    // The answers the file holds: the name of the constant, the answer it is (RealResponses), and the type in types.ts it must satisfy.
    private static readonly (string Constant, string Answer, string Type)[] Constants =
    [
        ("status", "status", "StatusResponse"),
        ("report", "report", "ReportResponse"),
        ("analysis", "analysis", "AnalysisResponse"),
        ("daily", "daily", "DailyResponse"),
        ("dailySources", "dailySources", "DailySourcesResponse"),
        ("settings", "settings", "SettingsResponse"),
        ("connectionTest", "connectionTest", "ConnectionTestResult"),
    ];

    private static readonly JsonSerializerOptions Pretty = new()
    {
        WriteIndented = true,
        IndentSize = 2,
        NewLine = "\n",
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    private static string FilePath => Path.Combine(ClientFiles.ClientDirectory(), "src", "testing", "server-responses.ts");

    [Fact]
    public async Task The_client_holds_the_servers_real_answers_as_they_are_today()
    {
        var generated = await GenerateAsync();

        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1") await File.WriteAllTextAsync(FilePath, generated, new UTF8Encoding(false));

        var committed = File.Exists(FilePath) ? await File.ReadAllTextAsync(FilePath) : "";
        Assert.True(
            generated == committed,
            $"Client/src/testing/server-responses.ts is not what the server answers today ({FirstDifference(generated, committed)}). "
            + $"Run the C# tests with {UpdateVariable}=1 and commit the file.");
    }

    [Fact]
    public async Task The_answers_come_out_the_same_on_every_run()
        => Assert.Equal(await GenerateAsync(), await GenerateAsync());

    /// <summary>The text of server-responses.ts: a header, one import, and each answer as the Management API writes it, typed.</summary>
    private static async Task<string> GenerateAsync()
    {
        var answers = await RealResponses.AllAsync();
        var text = new StringBuilder()
            .Append("// generated by ServerResponsesFileTests (C#); do not edit.\n")
            .Append("// The server's real answers, as the Management API writes them, typed against types.ts: tsc fails on any member that is extra,\n")
            .Append("// missing or null where the client does not expect it. To write the file again, run the C# tests with UPDATE_SERVER_RESPONSES=1.\n")
            .Append('\n')
            .Append($"import type {{ {string.Join(", ", Constants.Select(c => c.Type).Order(StringComparer.Ordinal))} }} from '../types';\n");

        foreach (var (constant, answer, type) in Constants)
        {
            var json = JsonNode.Parse(ManagementJson.Serialize(answers.Single(a => a.Name == answer).Value))!.ToJsonString(Pretty);
            text.Append('\n').Append($"export const {constant}: {type} = {json};\n");
        }

        return text.ToString();
    }

    private static string FirstDifference(string expected, string actual)
    {
        if (actual.Length == 0) return "the file is missing or empty";

        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        for (var i = 0; i < Math.Max(expectedLines.Length, actualLines.Length); i++)
        {
            var want = i < expectedLines.Length ? expectedLines[i] : "<end of file>";
            var have = i < actualLines.Length ? actualLines[i] : "<end of file>";
            if (want != have) return $"line {i + 1}: expected `{Shorten(want)}`, found `{Shorten(have)}`";
        }

        return "they differ";
    }

    private static string Shorten(string line) => line.Length <= 120 ? line : line[..120] + "...";
}
